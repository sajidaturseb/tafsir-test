(() => {
  const tt = document.getElementById('languageTt');
  const ru = document.getElementById('languageRu');
  if (!tt || !ru) return;
  const urlTt = new URL(location.href);
  urlTt.searchParams.delete('lang');
  const urlRu = new URL(location.href);
  urlRu.searchParams.set('lang', 'ru');
  tt.href = urlTt.toString();
  ru.href = urlRu.toString();
  const russian = new URLSearchParams(location.search).get('lang') === 'ru';
  (russian ? ru : tt).setAttribute('aria-current', 'page');
  if (!russian) return;
  document.documentElement.lang = 'ru';
  const set = (selector, value) => {
    const el = document.querySelector(selector);
    if (el) el.textContent = value;
  };
  const label = (selector, value) => {
    const el = document.querySelector(selector);
    if (el && el.firstChild?.nodeType === Node.TEXT_NODE) el.firstChild.textContent = value;
  };
  set('.brand strong', 'Уроки тафсира');
  set('.brand small', '29-й и 30-й джузы и «Аль-Фатиха»');
  set('#home .eyebrow', 'Закрепляем знания по тафсиру');
  set('#home h1', 'Уроки по сурам');
  set('#home .lead', 'Прочитайте пояснение к суре, повторите его по вопросам, затем пройдите тест и напишите свой ответ.');
  set('#home .teacher .eyebrow', 'Для преподавателя');
  set('#home .teacher h2', 'Ссылка на урок');
  set('#home .teacher > p:nth-of-type(2)', 'Выберите суру и группу, затем отправьте ученику готовую ссылку.');
  label('#home .teacher label.field:nth-of-type(1)', 'Сура');
  label('#home .teacher label.field:nth-of-type(2)', 'Группа');
  set('#copyLinkBtn', 'Скопировать ссылку');
  set('#home .teacher > p:last-child a', 'Журнал результатов →');
  set('#intro .eyebrow', 'Знакомство с уроком');
  document.getElementById('tafsirText')?.setAttribute('aria-label', 'Смысл и пояснение суры');
  set('#review .eyebrow span:first-child', 'Повторение по вопросам');
  set('#review .think', 'Сначала подумайте над ответом сами. Затем сравните его с пояснением.');
  set('#reviewAnswer strong', 'Ответ');
  set('#showAnswerBtn', 'Показать ответ');
  set('#identity .eyebrow', 'Данные ученика');
  set('#identity h1', 'Кто проходит тест?');
  set('#identity .lead', 'Напишите имя и фамилию и выберите группу, чтобы результат был записан правильно.');
  label('#identity .identity-grid label.field:first-child', 'Имя и фамилия');
  label('#identity .identity-grid label.field:nth-child(2)', 'Группа');
  document.getElementById('studentName')?.setAttribute('placeholder', 'Имя и фамилия');
  set('#identity .hint', 'Тест начнётся после ввода имени и выбора группы.');
  set('#startTestBtn', 'Начать тест');
  set('#quiz .open-note', 'Напишите ответ своими словами.');
  set('#nextQuizBtn', 'Проверить');
  set('#result .eyebrow', 'Урок завершён');
  set('#result h1', 'Машааллах, вы завершили урок!');
  set('#result .score-card:nth-child(1) span', 'Правильных ответов');
  set('#result .score-card:nth-child(2) span', 'Ошибок');
  set('#result .score-card:nth-child(3) span', 'Открытый ответ дан');
  set('#result .done-card strong', 'Открытый ответ');
  const step = document.querySelector('#result .action-step:not(#sendInstruction)');
  if (step) {
    const strong = document.createElement('strong');
    strong.textContent = 'Практический шаг:';
    step.replaceChildren(strong, document.createTextNode(' Выберите одно доброе дело, о котором напоминает эта сура, и постарайтесь совершить его.'));
  }
  set('#result .hint', 'Работа по этой суре завершена. Автоматического перехода к другой суре нет.');
  set('#sendResultBtn', 'Отправить ещё раз');
  set('#retryBtn', 'Пройти ещё раз');
  document.getElementById('teacherLink')?.setAttribute('aria-label', 'Готовая ссылка');
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = 'Сура «Аль-Фатиха»: смысл аятов, вопросы для повторения и тест на русском языке.';
})();
